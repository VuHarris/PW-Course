// Logic operators are used to perform logical operations on boolean values. They can be used to combine multiple conditions and return a single boolean value.

// Logical AND operator (&&) returns true if both operands are true, otherwise it returns false.
let a = true;
let b = false;
console.log(a && b); // Output: false

// Logical OR operator (||) returns true if at least one of the operands is true, otherwise it returns false.

console.log(a || b); // Output: true

// Logical NOT operator (!) is used to negate a boolean value.
console.log(!a); // Output: false
console.log(!b); // Output: true

// Mathematical operators can also be used in conjunction with logical operators to create more complex expressions.
let x = 5;
let y = 10;
console.log(x > 3 && y < 15); // Output: true
console.log(x < 3 || y > 15); // Output: false      

